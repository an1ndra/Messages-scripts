#!/usr/bin/env python3
"""Build one listing frame, and optionally save it as an editable .pcraft.

The published screenshots are generated by make-fdroid-name-set.py, but editing
one by hand needs a document you can open: this writes the same frame with the
phone screen as a *smart object* (Layer > Smart Objects > Replace Contents) and
the two text blocks as live type layers, so nothing has to be rebuilt by hand.

    # a finished PNG
    python3 scripts/make-listing-frame.py --raw ~/shot.png --out frame.png \\
        --headline "Search messages" --subhead "Find a word across every chat."

    # the same frame as an editable document
    python3 scripts/make-listing-frame.py --raw ~/shot.png --out frame.pcraft \\
        --headline "Search messages" --subhead "Find a word across every chat."

    # dark screenshots use the slate backdrop
    ... --dark
"""
import argparse
import importlib.util
import json
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent

spec = importlib.util.spec_from_file_location(
    "mss", REPO / "scripts" / "make-store-screenshots.py")
mss = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mss)

DARK = {
    "bg_top": "#243452", "bg_mid": "#111A2B", "bg_bottom": "#05080F",
    "ink": "#FFFFFF", "frame": "#04060B", "button": "#0B1220", "shadow": "#000000",
}


def steps(raw, headline, subhead, colors):
    """mss.steps, but with a named smart-object screen and named text layers."""
    raw_w, raw_h = mss.png_size(raw)
    screen_h = round(raw_h * mss.SCREEN_W / raw_w)
    frame_h = screen_h + 2 * mss.BEZEL
    mid = mss.PHONE_TOP + 520
    return [
        ("gradient.fill.create",
         {"from": [mss.CANVAS_W // 2, 0], "to": [mss.CANVAS_W // 2, mss.CANVAS_H],
          "stops": [[0, colors["bg_top"]], [0.55, colors["bg_mid"]],
                    [1, colors["bg_bottom"]]]}),
        ("type.create",
         {"box": mss.HEADLINE_BOX, "align": "center", "text": headline, "font": mss.FONT,
          "weight": 800, "size": mss.HEADLINE_SIZE, "leading": mss.HEADLINE_LEADING,
          "tracking": mss.HEADLINE_TRACKING, "color": colors["ink"], "name": "Headline"}),
        ("type.create",
         {"box": mss.SUBHEAD_BOX, "align": "center", "text": subhead, "font": mss.FONT,
          "weight": 500, "size": mss.SUBHEAD_SIZE, "leading": mss.SUBHEAD_LEADING,
          "tracking": -10, "color": colors["ink"], "name": "Subhead"}),
        ("layer.setProps", {"opacity": 0.86}),
        ("shape.create",
         {"kind": "roundedRect", "rect": [mss.FRAME_X - 6, mid - 170, 12, 110],
          "radii": 5, "fill": colors["frame"], "name": "Volume up"}),
        ("shape.create",
         {"kind": "roundedRect", "rect": [mss.FRAME_X - 6, mid - 44, 12, 110],
          "radii": 5, "fill": colors["frame"], "name": "Volume down"}),
        ("shape.create",
         {"kind": "roundedRect", "rect": [mss.FRAME_X + mss.FRAME_W - 6, mid - 120, 12, 150],
          "radii": 5, "fill": colors["frame"], "name": "Power"}),
        ("shape.create",
         {"kind": "roundedRect", "rect": [mss.FRAME_X, mss.PHONE_TOP, mss.FRAME_W, frame_h],
          "radii": 72, "fill": colors["frame"], "name": "Bezel"}),
        ("layer.select", {"layer": "Bezel"}),
        ("layer.layerStyle.dropShadow",
         {"color": colors["shadow"], "opacity": 34, "blend": "multiply",
          "angle": 90, "distance": 30, "size": 90}),
        ("shape.create",
         {"kind": "roundedRect", "rect": [mss.SCREEN_X, mss.SCREEN_Y, mss.SCREEN_W, screen_h],
          "radii": 48, "fill": "#FFFFFF", "name": "Screen clip"}),
        # smartObject: the phone screen stays replaceable in an editor
        ("file.placeEmbedded",
         {"path": str(raw), "scale": mss.SCREEN_W / raw_w * 100,
          "center": [mss.CANVAS_W // 2, mss.SCREEN_Y + screen_h // 2], "smartObject": True}),
        ("layer.createClippingMask", {}),
    ]


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--raw", required=True, help="emulator screenshot to place")
    ap.add_argument("--out", required=True, help=".png for an export, .pcraft for an editable doc")
    ap.add_argument("--headline", required=True)
    ap.add_argument("--subhead", required=True)
    ap.add_argument("--dark", action="store_true", help="slate backdrop for dark screenshots")
    args = ap.parse_args()

    raw = Path(args.raw).expanduser().resolve()
    if not raw.exists():
        sys.exit(f"make-listing-frame: {raw} does not exist")
    out = Path(args.out).expanduser()
    out.parent.mkdir(parents=True, exist_ok=True)

    colors = DARK if args.dark else mss.palette()
    cmd = ["photocraft-cli", "run", "--new",
           '{"width": %d, "height": %d, "background": "#FFFFFF"}' % (mss.CANVAS_W, mss.CANVAS_H)]
    for name, params in steps(raw, args.headline, args.subhead, colors):
        cmd += ["--cmd", name, "--params", json.dumps(params)]
    cmd += ["--out", str(out)]
    result = subprocess.run(cmd, capture_output=True, text=True)
    if result.returncode != 0:
        sys.exit(f"make-listing-frame: failed\n{result.stdout}\n{result.stderr}")
    print(f"wrote {out}")
    if out.suffix == ".pcraft":
        print("  open it, select the placed screen layer, Layer > Smart Objects > "
              "Replace Contents, then edit Headline / Subhead")
    return 0


if __name__ == "__main__":
    sys.exit(main())
